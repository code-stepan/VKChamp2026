print(f"Сообществ: {len(b):,} | ключевых блоков в key_numbers.json: {len(kn)}")

# %% [markdown]
# ## 1. Эффект доставки: PSM при разных калиперах и на разных контролях
#
# В ноутбуке 02 базовая спецификация — контроль только среди сообществ с чекаутом (S4),
# калипер 0,2 SD логита propensity score. Проверяем 8 комбинаций:
# контроль «с чекаутом» / «весь каталог» × калипер 0,05 / 0,1 / 0,2 / 0,4.

# %%
specs = []
for spec_name, restrict in [("контроль: с чекаутом", {"checkout": 1}),
                            ("контроль: весь каталог", None)]:
    for cm in [0.05, 0.1, 0.2, 0.4]:
        r = an.psm_effect(b, treatment="delivery", restrict=restrict, n_boot=400, caliper_mult=cm)
        e = r["effects"].set_index("outcome")
        specs.append({
            "спецификация": spec_name, "калипер (SD)": cm,
            "пар": r["n_matched_pairs"],
            "ATT активации, п.п.": e.loc["sell_rate", "ATT"] * 100,
            "ДИ низ, п.п.": e.loc["sell_rate", "ATT_ci_low"] * 100,
            "ДИ верх, п.п.": e.loc["sell_rate", "ATT_ci_high"] * 100,
            "ATT заказов/бизнес": e.loc["orders_per_biz", "ATT"],
            "ATT GMV/бизнес, ₽": e.loc["gmv_per_biz", "ATT"],
        })
psm_grid = pd.DataFrame(specs)
data.save_table(psm_grid, "05_psm_robustness")
psm_grid.round(3)

# %%
fig, ax = plt.subplots(figsize=(10, 4.6))
y = np.arange(len(psm_grid))
ax.errorbar(psm_grid["ATT активации, п.п."], y,
            xerr=[psm_grid["ATT активации, п.п."] - psm_grid["ДИ низ, п.п."],
                  psm_grid["ДИ верх, п.п."] - psm_grid["ATT активации, п.п."]],
            fmt="o", color=VK, ecolor="#B9C6DA", capsize=3, ms=6)
ax.axvline(0, color=BAD, ls="--", lw=1)
ax.set_yticks(y, [f"{r['спецификация']}, caliper={r['калипер (SD)']}" for _, r in psm_grid.iterrows()])
ax.set_xlabel("ATT по вероятности первой продажи, п.п. (95% ДИ)")
ax.set_title("Эффект доставки устойчив по знаку, но во всех спецификациях ДИ включает ноль")
fig.tight_layout(); viz.save(fig, "05_psm_robustness")

# %% [markdown]
# **Чтение результата.**
# * Точечная оценка активации **+2,8…+3,5 п.п.** во всех 8 спецификациях — направление устойчиво.
# * **Во всех 8 спецификациях 95% ДИ включает ноль** (нижние границы −0,7…0,0 п.п.).
# * По **объёму заказов ATT отрицательный** (−0,3…−1,1 заказа на бизнес) во всех спецификациях.
# * По GMV — также без положительного эффекта.
#
# Отсюда корректная формулировка: **доставка снимает барьер первой сделки, но не создаёт спрос.**
# Обещать «подключим доставку — продажи вырастут втрое» нельзя; проверять A/B-тестом.
#
# Оговорка: интервал построен парным бутстрэпом по сопоставленным парам и **не учитывает
# неопределённость самого сопоставления**; с её учётом ДИ был бы шире, то есть вывод
# «эффект не доказан» только усиливается. В ковариатах нет тематики — баланс по ней не гарантирован.

# %% [markdown]
# ## 2. S4 vs S5: наивный разрыв значим, но группы несопоставимы
#
# «Сообщества с доставкой продают в 3,2 раза чаще» — проверим значимость и состав групп.
# Разница долей тестируется z-тестом, интервал — методом Newcombe.

# %%
prof = an.segment_profile(b).set_index("segment")
s4 = prof.loc["S4. Каталог + чекаут"]
s5 = prof.loc["S5. Каталог + чекаут + доставка"]
s56_n = s5.n + prof.loc["S6. Полный стек (+оплата)", "n"]
s56_sellers = s5.sellers + prof.loc["S6. Полный стек (+оплата)", "sellers"]

tp_s5 = an.two_prop_test(s5.sellers, s5.n, s4.sellers, s4.n)
tp_s56 = an.two_prop_test(s56_sellers, s56_n, s4.sellers, s4.n)
gap_test = pd.DataFrame([
    {"сравнение": "S5 (доставка) vs S4 (без доставки)",
     "доля 1": tp_s5["p1"], "доля 2": tp_s5["p2"], "разница, п.п.": tp_s5["diff"] * 100,
     "ДИ низ, п.п.": tp_s5["diff_ci_low"] * 100, "ДИ верх, п.п.": tp_s5["diff_ci_high"] * 100,
     "отношение": tp_s5["ratio"], "p-value": tp_s5["p_value"]},
    {"сравнение": "S5+S6 vs S4",
     "доля 1": tp_s56["p1"], "доля 2": tp_s56["p2"], "разница, п.п.": tp_s56["diff"] * 100,
     "ДИ низ, п.п.": tp_s56["diff_ci_low"] * 100, "ДИ верх, п.п.": tp_s56["diff_ci_high"] * 100,
     "отношение": tp_s56["ratio"], "p-value": tp_s56["p_value"]},
])
data.save_table(gap_test, "05_segment_gap_test")
gap_test.round(4)

# %%
comp = pd.DataFrame([
    ["медиана подписчиков", s4.subs_median, s5.subs_median],
    ["медиана активных SKU", s4.sku_median, s5.sku_median],
    ["медиана публикаций за 30 дней", s4.content_median, s5.content_median],
    ["доля с товарным контентом", s4.prod_content_share, s5.prod_content_share],
    ["доля продающих", s4.sell_rate, s5.sell_rate],
], columns=["показатель", "S4. Каталог + чекаут", "S5. Каталог + доставка"])
data.save_table(comp, "05_s4_vs_s5_profile")
comp.round(4)

# %% [markdown]
# **Вывод.** Наивный разрыв **статистически значим** (+11,8 п.п., ×3,2, p < 0,001),
# но группы различаются по ассортименту в 4,3 раза (39 vs 9 SKU) и по охвату.
# Значит, тест подтверждает не эффект инструмента, а **разную зрелость продавцов**.
# Именно поэтому основной оценкой остаётся PSM, а не наивное сравнение.

# %% [markdown]
# ## 3. Разрыв Маркет vs Партнёр: состав трафика или механика карточки?
#
# Конверсия открытие → заказ: **0,21% у Маркета против 5,67% у Партнёра** (×26).
# Проверяем разложение:
#
# `конверсия = Σ (доля категории × конверсия внутри категории)`
#
# * **эффект состава** — если бы у Маркета был микс открытий Партнёра, но его собственные
#   внутрикатегорийные конверсии;
# * **эффект механики** — всё, что остаётся и воспроизводится внутри каждой категории.

# %%
dec = an.category_mix_decomposition(d["categories"])
data.save_table(dec["summary"], "05_gap_mix_vs_within")
data.save_table(dec["by_category"], "05_gap_by_category")
print(f"Категорий в расчёте: {dec['n_categories']}")
print(f"Конверсия Маркета: {dec['conv_vk']:.4%} | Партнёра: {dec['conv_pt']:.4%} | "
      f"контрфактика (микс Партнёра × механика Маркета): {dec['conv_counterfactual']:.4%}")
dec["summary"].round(4)

# %%
fig, ax = plt.subplots(figsize=(9.5, 4))
s = dec["summary"].iloc[:2]
colors = [BAD if v < 0 else GOOD for v in s.share_of_log_gap]
ax.barh(s.компонента, s.share_of_log_gap * 100, color=colors, height=0.55)
for i, (v, r) in enumerate(zip(s.share_of_log_gap * 100, s.ratio)):
    ax.text(v, i, f"  {v:+.0f}%  (×{r:.2f})", va="center", fontweight="bold")
ax.axvline(0, color="#1F2733", lw=1)
ax.set_xlabel("вклад в логарифмический разрыв конверсии, %")
ax.set_title("Разрыв VK vs Партнёр: механика карточки, а не состав категорий")
ax.margins(x=0.25)
fig.tight_layout(); viz.save(fig, "05_gap_mix_vs_within")

# %% [markdown]
# **Результат, меняющий акцент в презентации.**
# * Состав трафика объясняет **−14%** логарифмического разрыва: он скорее **помогает** Маркету,
#   потому что у него выше доля «Продуктов питания» и ниже — «Ремонта».
# * Механика внутри категорий объясняет **114%**: разрыв **воспроизводится во всех товарных
#   категориях** (отношение конверсий ×6…×315); исключение — служебная корзина «Другое»,
#   у Партнёра в ней ноль заказов.
#
# То есть **46% «мёртвого трафика» — это проблема объёма и релевантности ассортимента,
# но не объяснение низкой конверсии**. Главный вывод ноутбука 03 сохраняется:
# карточка Маркета не доводит до сделки. Оговорка: суммы заказов по категориям расходятся
# с итогами на 5–7%, поэтому смотрим на структуру, а не на абсолютные значения.
# В разложение входят 17 категорий, где есть открытия у обоих сегментов, поэтому итоговое
# отношение здесь 22,7, а не 26,5 по полным данным; на вывод о вкладе механики это не влияет.

# %% [markdown]
# ## 4. Тренды: проверка на календарный артефакт
#
# «Заказы Маркета −10,7%, Партнёра +18% за месяц» — это сравнение первых и последних 7 дней.
# В 30-дневном окне такой расчёт чувствителен к тому, какие дни недели попали в края.
# Оцениваем **log(метрика) ~ день + фиксированные эффекты дня недели** с HAC-ошибками.

# %%
metrics = ["Заказы: Маркет Вконтакте", "GMV, ₽: Маркет Вконтакте",
           "Заказы: Партнёр 1", "GMV, ₽: Партнёр 1", "Открытия карточки: Партнёр 1"]
tr = pd.DataFrame([an.trend_adjusted(d["daily"], m) for m in metrics])
tr["дневной темп, %"] = tr.daily_pct * 100
tr["ДИ низ, %/день"] = tr.daily_pct_ci_low * 100
tr["ДИ верх, %/день"] = tr.daily_pct_ci_high * 100
tr["за 30 дней, %"] = ((1 + tr.daily_pct) ** 30 - 1) * 100
tr["raw change, %"] = tr.change_pct_raw * 100
data.save_table(tr, "05_trends_adjusted")
tr[["metric", "дневной темп, %", "ДИ низ, %/день", "ДИ верх, %/день",
    "за 30 дней, %", "raw change, %", "p_value_adjusted", "p_value_raw", "r2"]].round(4)

# %%
fig, ax = plt.subplots(figsize=(10, 4.2))
order = tr.sort_values("дневной темп, %")
y = np.arange(len(order))
colors = [GOOD if v > 0 else BAD for v in order["дневной темп, %"]]
ax.errorbar(order["дневной темп, %"], y,
            xerr=[order["дневной темп, %"] - order["ДИ низ, %/день"],
                  order["ДИ верх, %/день"] - order["дневной темп, %"]],
            fmt="o", color=VK, ecolor="#B9C6DA", capsize=3, ms=6)
ax.scatter(order["дневной темп, %"], y, c=colors, s=55, zorder=3)
ax.axvline(0, color="#1F2733", lw=1)
ax.set_yticks(y, order.metric)
ax.set_xlabel("средний дневной темп, % (после поправки на день недели; 95% ДИ)")
ax.set_title("Направления трендов сохраняются после поправки на календарь")
fig.tight_layout(); viz.save(fig, "05_trends_adjusted")

# %% [markdown]
# **Вывод.** Поправка на день недели **не меняет картину**:
# заказы Маркета падают (≈−0,5%/день, p≈0,008), заказы Партнёра растут (≈+0,7%/день, p≈0,002),
# GMV Партнёра +1,8%/день (p<0,001). За 30 дней это ≈−13% у Маркета и ≈+24% у Партнёра.
# Сырые «первые 7 к последним 7» дают близкие, но чуть другие цифры (−10,7% / +18%) — их и
# оставляем на слайде как простое чтение, а в приложении показываем модель.

# %% [markdown]
# ## 5. Контентный вывод: устойчив ли он к выбросам и рекламе
#
# Парное сравнение «товарный vs обычный контент внутри одного сообщества» дало ×1,9 по охвату.
# Проверяем четыре среза: все пары, без топ-1% по подписчикам, только органика,
# и оба ограничения одновременно.

# %%
variants = [
    ("все пары", b, False),
    ("без топ-1% по подписчикам", b[b.subs < b.subs.quantile(0.99)], False),
    ("только без рекламы", b, True),
    ("без топ-1% и без рекламы", b[b.subs < b.subs.quantile(0.99)], True),
]
rows = []
for name, frame, organic in variants:
    _, st = an.content_paired(frame, organic_only=organic)
    rows.append({
        "срез": name, "пар": st["n_paired"],
        "просмотров/пост: товарный": st["vpp_prod_median"],
        "просмотров/пост: обычный": st["vpp_reg_median"],
        "отношение": st["vpp_ratio_median"],
        "доля пар, где товарный хуже по охвату": st["vpp_prod_worse_share"],
        "отношение ER": st["er_ratio_median"],
        "p Wilcoxon (охват)": st["vpp_wilcoxon_p"],
    })
content_rob = pd.DataFrame(rows)
data.save_table(content_rob, "05_content_robustness")
content_rob.round(4)

# %% [markdown]
# **Вывод.** Отношение охвата держится на уровне **1,90–1,97** во всех срезах,
# отношение ER — **0,54** (товарный хуже по вовлечению). Это не эффект нескольких крупных
# сообществ и не эффект рекламодателей.

