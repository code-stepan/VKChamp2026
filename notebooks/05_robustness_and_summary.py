# %% [markdown]
# # 05 · Проверка устойчивости выводов и итоговая сборка
#
# Анализ в ноутбуках 00–04 закончен. Здесь мы делаем то, что обычно пропускают:
# **проверяем, выдерживают ли главные выводы смену спецификации**.
# Кейс требует «data-driven выводов, а не несколько красивых графиков»,
# поэтому каждое число, которое пойдёт на слайд, должно иметь:
#
# 1. источник (таблица в `outputs/tables`);
# 2. проверку на устойчивость (другая спецификация / подвыборка);
# 3. явную формулировку, чего утверждать **нельзя**.
#
# ## Что проверяем
# * **A. Эффект доставки (PSM)** — не является ли +3,2 п.п. артефактом калипера и выбора контроля.
# * **B. Разрыв S4 vs S5** — значим ли наивный «×3,2» и чем он объясняется.
# * **C. Разрыв Маркет vs Партнёр** — это состав трафика или механика карточки.
# * **D. Тренды за месяц** — не объясняются ли они структурой дней недели.
# * **E. Контентный вывод** — держится ли «товарный охват выше в 1,9 раза» без выбросов и рекламодателей.

# %%
