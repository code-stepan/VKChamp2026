    ["MAU Маркета", mau],
    ["DAU/MAU Маркета", dau / mau],
    ["DAU Маркета / DAU VK (90,8 млн)", dau / VK_DAU_2026Q3],
    ["Видели товары за 30 дней (вся платформа)", saw],
    ["Открывали карточку за 30 дней (вся платформа)", opened],
