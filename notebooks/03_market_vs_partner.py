import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from vkcase import data, analysis as an, viz
from vkcase.config import VK, PARTNER, GOOD, BAD, GREY, VK_DAU_2026Q3

pd.set_option("display.width", 250)
pd.set_option("display.max_columns", 60)
# %matplotlib inline

d = data.load_all()
t, day, src, cat, byr, reg = d["totals"], d["daily"], d["sources"], d["categories"], d["buyers"], d["regions"]
num = lambda m, c="Маркет Вконтакте": float(pd.to_numeric(pd.Series([t.loc[m, c]]), errors="coerce").iloc[0])

# %% [markdown]
# ## 1. Две воронки: одинаковый трафик, разная судьба покупателя

# %%
f = an.funnel_table(t)
data.save_table(f, "03_funnel")
viz.funnel_compare(f)
f.T.rename(columns={0: "Маркет ВКонтакте", 1: "Партнёр 1"}).round(4)

# %%
viz.step_conversion_bars(f)

# %% [markdown]
# **Факты:**
# * Маркет получает **в 2,2 раза больше открытий карточки** (193,5 млн против 86,9 млн) — интерес есть.
# * Но заказов **в 11,9 раза меньше** (414 тыс. против 4,93 млн).
# * Провал на шаге **«открытие карточки → нажатие кнопки»**: 3,08% против 42,16% — **разрыв ×13,7**.
# * Средний чек Маркета **3 781 ₽** против **1 039 ₽** у Партнёра (×3,6) — другая корзина.
#
# Пользователь ВКонтакте **хочет смотреть товары**, но в карточке Маркета **не видит действия, которое ведёт к покупке**.

# %%
gap = an.gap_decomposition(f)
data.save_table(gap, "03_gap_decomposition")
fig, ax = plt.subplots(figsize=(10, 4))
colors = [GOOD if v > 0 else BAD for v in gap.log_contribution]
ax.barh(gap.step, gap.log_contribution * 100, color=colors, height=0.6)
for i, v in enumerate(gap.log_contribution * 100):
    ax.text(v, i, f"  {v:+.1f}%", va="center", fontsize=10, fontweight="bold")
ax.axvline(0, color="#1F2733", lw=1)
ax.set_xlabel("вклад в логарифмический разрыв по заказам, % (сумма = 100%)")
ax.set_title("Почему Партнёр делает в 11,9 раза больше заказов: декомпозиция")
ax.margins(x=0.18)
fig.tight_layout(); viz.save(fig, "03_gap_decomposition")
gap.assign(log_contribution=lambda x: (x.log_contribution*100).round(1))

# %% [markdown]
# > **Это главный слайд проблематики.**
# > **106% разрыва** по заказам объясняется одним шагом — «открытие карточки → нажатие кнопки».
# > Более того, по CTR «показ → открытие» Маркет **лучше** Партнёра (4,05% против 1,52%, вклад −40%):
# > трафик и интерес — не проблема. Проблема — **карточка не продаёт**.
# >
# > Что стоит за шагом «нажатие кнопки»: в Маркете кнопка чаще ведёт в переписку с продавцом
# > или на внешний ресурс, у Партнёра — в корзину с оплатой и доставкой.
# > Отсюда продуктовый приоритет №1: **сделать карточку товарной сделкой, а не объявлением**.

# %% [markdown]
# ### 1.1. Что мы не видим: заказ, оплата и внешний сайт

# %%
obs = pd.DataFrame([
    ["Оформленные заказы Маркета", num("Оформленные заказы")],
    ["Оплаченные заказы Маркета", num("Оплаченные заказы")],
    ["Доля оплаченных", num("Оплаченные заказы") / num("Оформленные заказы")],
    ["Прямые переходы к Партнёру без открытия карточки", num("Прямые переходы к Партнёру 1 (без открытия карточки)", "Партнёр 1")],
    ["Заказы Партнёра / (нажатия + прямые переходы)",
     num("Оформленные заказы", "Партнёр 1") / (num("Нажатия на кнопку в карточке", "Партнёр 1") + num("Прямые переходы к Партнёру 1 (без открытия карточки)", "Партнёр 1"))],
], columns=["показатель", "значение"])
obs

# %% [markdown]
# У Партнёра **106,9 млн прямых переходов** на внешнюю площадку **без открытия карточки** —
# то есть контент ведёт мимо витрины VK сразу в корзину маркетплейса.
# ВКонтакте в этой схеме — **источник трафика**, а не место сделки.
# Это и есть ответ на вопрос Киры из кейса: *«а если продажа заканчивается на внешнем сайте, мы её увидим?»* —
# > увидим только как «оформленный заказ», без оплаты, возвратов и выкупа.

# %% [markdown]
# ## 2. Источники трафика: интент против браузинга

# %%
s = src.copy()
s["type"] = np.where(s["Источник"].isin(["Лента", "Клипы"]), "контент (вдохновение)",
             np.where(s["Источник"] == "Поиск", "поиск (интент)", "витрина/браузинг"))
data.save_table(s, "03_sources")
viz.grouped_share(s.sort_values("share_vk", ascending=False), "Источник", "share_vk", "share_pt",
                  "Структура открытий карточки по источникам", "03_sources")
s[["Источник", "Маркет Вконтакте", "share_vk", "Партнёр 1", "share_pt", "type"]].assign(
    share_vk=lambda x: (x.share_vk*100).round(1), share_pt=lambda x: (x.share_pt*100).round(1))

# %%
mix = s.groupby("type")[["share_vk", "share_pt"]].sum()
print((mix * 100).round(1).to_string())
print(f"\nРеферальные открытия Партнёра: {src.attrs['referral_opens']:,.0f} "
      f"({src.attrs['referral_opens']/num('Открытия карточки товара','Партнёр 1'):.1%} его открытий)")
print(f"Реферальные от всех открытий (Маркет + Партнёр): "
      f"{src.attrs['referral_opens']/(num('Открытия карточки товара')+num('Открытия карточки товара','Партнёр 1')):.1%}")

# %% [markdown]
# **Диагноз модели:**
# * Маркет: **79,5%** открытий — витрина, «Другое» и главная, то есть **браузинг без намерения купить**;
#   контент даёт лишь 18,6%, поиск — 1,9%.
# * Партнёр: **92,7%** — контент (клипы 74,7% + лента 18%), причём **94,8% его открытий реферальные**.
#
# Это две принципиально разные механики: **«полка в магазине»** против **«рекомендация автора»**.
# Данные говорят, что вторая конвертирует в заказ в 27 раз лучше (5,67% против 0,21%).

# %% [markdown]
# ## 3. Категории: где трафик есть, а продаж нет
#
# Здесь важно помнить оговорку из ноутбука 00: суммы заказов по категориям расходятся с итогами
# на 5–7%, поэтому смотрим **структуру**, а не абсолютные доли.

# %%
c = cat.sort_values("opens_vk", ascending=False).copy()
data.save_table(c, "03_categories")
c[["category", "opens_vk", "orders_vk", "conv_vk", "conv_pt", "conv_gap_x", "open_share_vk", "order_share_vk"]].assign(
    conv_vk=lambda x: (x.conv_vk*100).round(3), conv_pt=lambda x: (x.conv_pt*100).round(2),
    open_share_vk=lambda x: (x.open_share_vk*100).round(1),
    order_share_vk=lambda x: (x.order_share_vk*100).round(1)).round(2)

# %%
fig, ax = plt.subplots(figsize=(11, 5.2))
cc = c[c.opens_pt > 0].sort_values("conv_vk")
x = np.arange(len(cc)); w = 0.4
ax.bar(x - w/2, cc.conv_vk * 100, w, label="Маркет ВКонтакте", color=VK)
ax.bar(x + w/2, cc.conv_pt * 100, w, label="Партнёр 1", color=PARTNER)
ax.set_yscale("log"); ax.set_ylabel("конверсия открытие → заказ, % (лог. шкала)")
ax.set_xticks(x, cc.category, rotation=40, ha="right")
ax.set_title("Конверсия по категориям: разрыв системный, а не категориальный")
ax.legend()
fig.tight_layout(); viz.save(fig, "03_category_conversion")

# %%
dead = c[c.is_dead_traffic == 1]
dead_share_opens = dead.opens_vk.sum() / c.opens_vk.sum()
dead_share_orders = dead.orders_vk.sum() / c.orders_vk.sum()
print(f"Категории с конверсией <0,1%: {len(dead)} из {len(c)}")
print(f"Они забирают {dead_share_opens:.1%} открытий карточки Маркета и дают {dead_share_orders:.1%} заказов")
print("\nСписок:", ", ".join(dead.category))
print(f"\nКосинусная близость структуры: трафик Маркета vs заказы Маркета = {an.cosine(c.open_share_vk, c.order_share_vk):.3f}")
print(f"трафик Маркета vs заказы Партнёра = {an.cosine(c.open_share_vk, c.order_share_pt):.3f}")
print(f"заказы Маркета vs заказы Партнёра = {an.cosine(c.order_share_vk, c.order_share_pt):.3f}")

# %% [markdown]
# **Инсайт «мёртвый трафик».** Почти **половина открытий карточки Маркета (46%)** приходится на категории,
# где конверсия ниже 0,1%: «Другое» (29 млн открытий → 41 заказ), «Гардероб», «Транспорт»,
# «Недвижимость», «Бытовая техника», «Ремонт».
#
# Это не «плохие продавцы» — это **несоответствие ассортимента и намерения**:
# в Маркет заходят смотреть то, что покупают на классифайдах и маркетплейсах
# (недвижимость, авто, техника), а внутри VK сделка по таким товарам не поддерживается.
#
# При этом там, где товар «социальный» и импульсный, конверсия заметно выше:
# продукты питания 0,96%, хобби 0,35%, товары для животных 0,40%, канцелярия 0,42%.

# %% [markdown]
# ## 4. Кто покупает: аудитория и география

# %%
age = byr.groupby("age")[["buyers_vk", "buyers_pt"]].sum()
age_share = age / age.sum()
order = ["до 18", "18–24", "25–34", "35–44", "45–54", "55+", "н/д"]
age_share = age_share.reindex([i for i in order if i in age_share.index])
data.save_table(age_share.reset_index(), "03_age_shares")
viz.grouped_share(age_share.reset_index(), "age", "buyers_vk", "buyers_pt",
                  "Возрастная структура покупателей", "03_age")
sex = byr.groupby("sex")[["buyers_vk", "buyers_pt"]].sum()
print("Пол (доли):\n", (sex / sex.sum()).round(3).to_string())
print("\nВозраст (доли):\n", age_share.round(3).to_string())
print(f"\nДоля 35+: Маркет {(age_share.loc[['35–44','45–54','55+'],'buyers_vk'].sum()):.1%} | "
      f"Партнёр {(age_share.loc[['35–44','45–54','55+'],'buyers_pt'].sum()):.1%}")
print(f"Заказов на покупателя: Маркет {num('Оформленные заказы')/num('Уникальные покупатели за 30 дней'):.2f} | "
      f"Партнёр {num('Оформленные заказы','Партнёр 1')/num('Уникальные покупатели за 30 дней','Партнёр 1'):.2f}")
print(f"Доля повторных покупателей: Маркет {num('Доля повторных покупателей (2+ заказа), %')}% | "
      f"Партнёр {num('Доля повторных покупателей (2+ заказа), %','Партнёр 1')}%")

# %% [markdown]
# * Обе модели — **женские** (73–75%), ядро 35–44.
# * Маркет **моложе**: 18–34 дают 44% покупателей против 22% у Партнёра; у Партнёра 55+ — 20% против 9%.
# * Партнёр **удерживает лучше**: 1,7 заказа на покупателя и 26,6% повторных против 1,4 и 19%.
#
# Вывод: у Маркета есть аудитория молодых покупателей с более высоким чеком — это **не «мусорный» трафик**,
# а недоиспользованный актив. Но частота покупок ниже → нет привычки покупать внутри VK.

# %%
r = reg.dropna(subset=["buyers_vk"]).copy()
top = r.nlargest(12, "share_vk")
data.save_table(r, "03_regions")
viz.grouped_share(top, "region", "share_vk", "share_pt", "Топ-12 регионов по доле покупателей Маркета",
                  "03_regions", figsize=(12, 5))
msk_spb = ["г. Москва", "г. Санкт-Петербург"]
print(f"Москва + СПб: Маркет {r[r.region.isin(msk_spb)].share_vk.sum():.1%} | "
      f"Партнёр {reg[reg.region.isin(msk_spb)].share_pt.sum():.1%}")
print(f"HHI гео-концентрации: Маркет {an.hhi(r.share_vk):.4f} | Партнёр {an.hhi(r.share_pt):.4f}")
print("\nРегионы, где Маркет переиндексирован относительно Партнёра (доля VK / доля Партнёра):")
print(r.nlargest(8, "index_vk_vs_pt")[["region", "share_vk", "share_pt", "index_vk_vs_pt"]].round(4).to_string(index=False))

# %% [markdown]
# Маркет **более столичный** (18,6% против 10,4% в Москве и СПб) и в целом менее концентрирован
# по стране (HHI 0,036 против 0,146 — у Партнёра база шире по объёму, но сильнее смещена в топ-регионы).
# Переиндексированы industrial-регионы: Челябинская (×3,0), Пермский край (×2,4),
# Новгородская (×4,2), Свердловская (×1,8) — доля покупателей Маркета выше, чем у Партнёра.
#
# Практический смысл: **Маркет — канал регионального СМБ**, где у локального продавца
# нет альтернативы в виде федерального маркетплейса. Это аргумент за роль «витрина локального бизнеса».

