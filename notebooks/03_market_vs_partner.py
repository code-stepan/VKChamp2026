# но другая модель сделки. Сравнение показывает, что дело не в пользователях, а в механике.
#
# ## План
# 1. Две воронки и **декомпозиция разрыва** по заказам (где именно теряется покупатель).
# 2. Источники трафика: интент vs браузинг.
# 3. Категории: ассортиментный разрыв и «мёртвый трафик».
# 4. Аудитория и география: кто покупает.
# 5. Динамика за месяц: куда движутся две модели.
# 6. Роль Маркета: три альтернативы и выбор на данных.

