# %% [markdown]
# ### 4.1. Чувствительность: что важнее всего
#
# Меняем по одному параметру базового сценария на ±50% и смотрим влияние на заказы и на выручку.

# %%
base_p = SCEN["Базовый"].copy()
def orders_of(p):
    return BASE["opens"] * (1 + p["opens_growth"]) * p["click_rate"] * p["click2order"]
def revenue_of(p):
    o = orders_of(p); g = o * p["aov"]
    return g * p["paid_share"] * p["take_rate"]
base_orders, base_rev = orders_of(base_p), revenue_of(base_p)
sens = []
for key in ["click_rate", "click2order", "opens_growth", "aov", "paid_share", "take_rate"]:
    for mult, tag in [(0.5, "−50%"), (1.5, "+50%")]:
        p = base_p.copy(); p[key] = base_p[key] * mult
        sens.append({"параметр": key, "изменение": tag,
                     "заказы/мес": orders_of(p), "Δ заказов, %": orders_of(p)/base_orders-1,
                     "выручка от комиссии, ₽/мес": revenue_of(p), "Δ выручки, %": revenue_of(p)/base_rev-1})
sens = pd.DataFrame(sens)
data.save_table(sens, "04_sensitivity")
pivot = sens.pivot(index="параметр", columns="изменение", values="Δ выручки, %").reindex(
    ["click_rate", "click2order", "paid_share", "take_rate", "aov", "opens_growth"])[["−50%", "+50%"]]
fig, ax = plt.subplots(figsize=(9, 4.4))
y = np.arange(len(pivot))
ax.barh(y - 0.2, pivot["−50%"] * 100, 0.38, label="параметр −50%", color=BAD)
ax.barh(y + 0.2, pivot["+50%"] * 100, 0.38, label="параметр +50%", color=GOOD)
ax.set_yticks(y, pivot.index); ax.axvline(0, color="#1F2733", lw=1)
ax.set_xlabel("изменение выручки от комиссии, %")
ax.set_title("Чувствительность базового сценария (по одному параметру)")
ax.legend()
fig.tight_layout(); viz.save(fig, "04_sensitivity")
sens.round(3)

