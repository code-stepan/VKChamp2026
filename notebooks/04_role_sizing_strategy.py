# %% [markdown]
# ## 4. Монетизация: от «продажи трафика» к «участию в сделке»
#
# Сегодня VK зарабатывает на рекламе, но данные показывают: **92% рекламодателей выборки
# не получают измеримого заказа**, а связь трат с продажей статистически не значима (OR≈1,02).
# Значит модель «продавать трафик» упирается в потолок: бизнес не видит результата.
#
# Целевая модель — **три потока**, каждый из которых возможен только после замыкания сделки.

# %%
